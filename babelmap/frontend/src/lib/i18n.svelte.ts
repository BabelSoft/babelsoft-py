/** Get a translated string by key. Falls back to English if translation missing. */
export function t(key: string): string {
  const locale = lang.v;
  const dict = translations[locale];
  if (dict && key in dict) return dict[key];
  // Fallback to English
  if (locale !== "en" && translations.en && key in translations.en) return translations.en[key];
  // Last resort: return key itself
  return key;
}

