/** The ASCII/CP1252 character a symbol glyph stands for (`GetAsciiMappingForSymbol`). */
export function asciiMappingForSymbol(cp: number): number {
  if (cp < SYMBOL_MAPPING_START || cp > SYMBOL_MAPPING_END) return cp;
  return SYMBOL_FONT_MAPPING[cp - SYMBOL_MAPPING_START];
}

/** The symbol PUA code point for an ASCII character (`GetSymbolMappingForAscii`). */
export function symbolMappingForAscii(cp: number): number {
  const i = SYMBOL_FONT_MAPPING.indexOf(cp);
  return i < 0 ? cp : SYMBOL_MAPPING_START + i;
}

/** True when `cp` falls inside the range symbol fonts actually populate. */
export function isSymbolPua(cp: number): boolean {
  return cp >= SYMBOL_MAPPING_START && cp <= SYMBOL_MAPPING_END;
}

/**
 * The character to *display* for `cp` given the current mode.
 *
 * Only PUA code points inside the symbol range are remapped, and only when the
 * toggle is on — every other character passes straight through.
 */
export function displayChar(cp: number, symbolMapping: boolean): string {
  const out = symbolMapping ? asciiMappingForSymbol(cp) : cp;
  return String.fromCodePoint(out);
}
