/**
 * Symbol-font mappings — a direct port of `Main/SymbolMappings.cpp`.
 *
 * Windows "symbol" fonts (Wingdings, Symbol, Webdings, …) do not use Unicode
 * in their `cmap`: they expose 224 glyphs at the private-use code points
 * U+F020–U+F0FF, and the *meaning* of each is the byte value `cp & 0xFF` read
 * through the Windows "Symbol" character set — i.e. ASCII for U+F020–U+F07F and
 * CP1252 for U+F080–U+F0FF.
 *
 * So when BabelMap shows U+F041 with a symbol font and "Show Symbol Font
 * Mappings" is on, it displays **A** — the ASCII character the glyph was
 * designed for — which is the only way to read such a font.
 *
 * The table below is byte-for-byte the original `SymbolFontMapping[]` array;
 * only 27 of the 224 entries deviate from a plain `cp & 0xFF` (the CP1252
 * replacements such as U+F080 → U+20AC EURO SIGN), so keeping the literal
 * table rather than the formula is deliberate.
 */

/** Inclusive PUA range that symbol fonts populate. */
export const SYMBOL_MAPPING_START = 0xf020;
export const SYMBOL_MAPPING_END = 0xf0ff;
export const SYMBOL_MAPPING_COUNT = 224;

