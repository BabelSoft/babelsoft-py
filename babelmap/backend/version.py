"""Unicode version statistics — Version History + per-version block lists.

The version-history statistics (scripts/blocks/assigned/… per release) live in
``data/scripts/unicode_version_stats.tsv`` (regenerated by
``tools/compute_version_stats.py``); derived columns follow
``CDialogVersions::FillHistoryList``.  Block tables are read from each version's
own UCD (Blocks.txt + UnicodeData under data/unicode/); 1.0.0/1.0.1 come from
``data/scripts/unicode_1_0_blocks.tsv`` + the reconstructed repertoire.
"""

from __future__ import annotations

import bisect
import functools
from pathlib import Path

from babelsoft.unicode.core import Unicode
from babelsoft.utils_.dirs import Dirs
from babelsoft.utils_.parser import parse_codepoint
from babelsoft.utils_.versions import VERSION_DIRS

# ---------------------------------------------------------------------------
# Data-driven block tables for Unicode 1.0.0 / 1.0.1.
#
# These two early versions predate DerivedAge.txt.  Their per-character
# repertoire is reconstructed by Ken Whistler at
#   https://www.unicode.org/Public/reconstructed/{1.0.0,1.0.1}/UnicodeData.txt
# (downloaded into data/unicode/reconstructed/ by babelsoft/utils_/sync.py via
# ``sync_unicode``).  That data carries NO block information, so the historical
# block *boundaries* are kept as data in data/scripts/unicode_1_0_blocks.tsv
# (not hardcoded).  Character counts are always computed from the reconstructed
# repertoire at load time.
# ---------------------------------------------------------------------------

_1_0_BLOCKS_FILE = Dirs.DATA / "scripts" / "unicode_1_0_blocks.tsv"


@functools.lru_cache(maxsize=1)
def _historical_blocks() -> dict[str, list[dict]]:
    """Load the 1.0.0/1.0.1 block boundary tables from data/scripts/.

    Each data row is: <table>\\t<name>\\t<start U+XXXX>\\t<end U+XXXX>\\t<introduced>.
    """
    result: dict[str, list[dict]] = {}
    for raw in Path(_1_0_BLOCKS_FILE).read_text(encoding="utf-8").splitlines():
        line = raw.strip()
        if not line or line.startswith("#"):
            continue
        table, name, start, end, introduced = line.split("\t")
        result.setdefault(table, []).append(
            {
                "name": name,
                "start": parse_codepoint(start),
                "end": parse_codepoint(end),
                "version": introduced,
            }
        )
    return result


# ---------------------------------------------------------------------------
# Per-version statistics (Unicode Version History).
#
# Values live in data/scripts/unicode_version_stats.tsv (one row per downloaded
# snapshot, regenerated by tools/compute_version_stats.py).  Derived columns
# are computed exactly as the C++ CDialogVersions::FillHistoryList:
#
#   Encoded   = graphic + format + control
#   Named     = graphic + format
#   Total     = total_planes * 65536
#   Assigned  = Encoded + pua + nonchar + surrogate
#   Unassigned= Total - Assigned
#   Added     = added
# ---------------------------------------------------------------------------

_VERSION_STATS_FILE = Dirs.DATA / "scripts" / "unicode_version_stats.tsv"


@functools.lru_cache(maxsize=1)
def _version_stats() -> list[dict]:
    """Load the per-version statistics table from data/scripts/.

    Row fields: version, date, total_planes, planes_in_use, scripts, blocks,
    graphic, control, format, pua, nonchar, surrogate, added, removed.
    """
    rows: list[dict] = []
    for raw in Path(_VERSION_STATS_FILE).read_text(encoding="utf-8").splitlines():
        line = raw.strip()
        if not line or line.startswith("#"):
            continue
        (
            version,
            date,
            total_planes,
            _planes,
            scripts,
            blocks,
            graphic,
            control,
            format,
            pua,
            nonchar,
            surrogate,
            added,
            _removed,
        ) = line.split("\t")
        rows.append(
            {
                "version": version,
                "date": date,
                "total_planes": int(total_planes),
                "scripts": int(scripts),
                "blocks": int(blocks),
                "graphic": int(graphic),
                "control": int(control),
                "format": int(format),
                "pua": int(pua),
                "nonchar": int(nonchar),
                "surrogate": int(surrogate),
                "added": int(added),
            }
        )
    return rows


@functools.lru_cache(maxsize=1)
def version_history(blocks_path: str) -> list[dict]:
    """Return per-Unicode-version cumulative statistics (the Version History).

    ``blocks_path`` is accepted for backward compatibility and ignored; all
    values come from data/scripts/unicode_version_stats.tsv.
    """
    history: list[dict] = []
    for s in _version_stats():
        encoded = s["graphic"] + s["format"] + s["control"]
        named = s["graphic"] + s["format"]
        total = s["total_planes"] * 0x10000
        assigned = encoded + s["pua"] + s["nonchar"] + s["surrogate"]
        history.append(
            {
                "version": s["version"],
                "date": s["date"],
                "scripts": s["scripts"],
                "blocks": s["blocks"],
                "total": total,
                "assigned": assigned,
                "unassigned": total - assigned,
                "named": named,
                "graphic": s["graphic"],
                "format": s["format"],
                "control": s["control"],
                "pua": s["pua"],
                "nonchar": s["nonchar"],
                "surrogate": s["surrogate"],
                "added": s["added"],
            }
        )
    return history


_DEFAULT_BLOCKS = str(Path(__file__).resolve().parent / "blocks.json")


def get_version_history() -> list[dict]:
    """Return the full Unicode version-history table (1.0.0 … current)."""
    return version_history(_DEFAULT_BLOCKS)


_RECONSTRUCTED_DIR = Dirs.RECONSTRUCTED


@functools.lru_cache(maxsize=4)
def _reconstructed_codepoints(version: str) -> set[int] | None:
    """Parse a reconstructed UnicodeData file → set of *named* codepoints.

    - `<..., First>` / `<..., Last>` ranges are expanded to their full span.
    - Unnamed `<control>` entries (C1 controls in Latin-1 Supplement, etc.)
      are excluded, matching the historical BabelMap character counts.
    Returns None when the file is not present.
    """
    path = _RECONSTRUCTED_DIR / version / "UnicodeData.txt"
    if not path.exists():
        return None

    cps: set[int] = set()
    first_cp: int | None = None

    for raw in path.read_text(encoding="utf-8").splitlines():
        line = raw.strip()
        if not line or line.startswith("#"):
            continue
        fields = line.split(";")
        cp = int(fields[0], 16)
        name = fields[1]

        if name.startswith("<") and name.endswith(", First>"):
            first_cp = cp
            continue
        if name.startswith("<") and name.endswith(", Last>"):
            if first_cp is not None:
                cps.update(range(first_cp, cp + 1))
                first_cp = None
            continue
        if name == "<control>":
            continue

        cps.add(cp)

    return cps


def _reconstructed_blocks(version: str) -> list[dict] | None:
    """Build the block table for 1.0.0/1.0.1 from reconstructed data.

    Block boundaries come from data/scripts/unicode_1_0_blocks.tsv; ``chars``
    is computed from the actual reconstructed repertoire.  Returns None if the
    reconstructed data file is unavailable.
    """
    boundaries = _historical_blocks().get(version)
    cps = _reconstructed_codepoints(version)
    if boundaries is None or cps is None:
        return None

    result: list[dict] = []
    for b in boundaries:
        chars = sum(1 for cp in cps if b["start"] <= cp <= b["end"])
        result.append(
            {
                "name": b["name"],
                "start": b["start"],
                "end": b["end"],
                "chars": chars,
                "version": b["version"],
            }
        )
    return result


# ─────────────────────────────────────────────────────────────────────────────
# Per-version block tables — read from each version's own UCD.
#
# Each version's Blocks.txt supplies block boundaries/names and its UnicodeData
# supplies the assigned repertoire used to count characters per block.  Versions
# without a Blocks.txt inherit the nearest older version's block list; versions
# whose data is unusable (1.1.5 is compressed, 3.1.1 ships no UnicodeData)
# inherit the previous version's full table.  1.0.0/1.0.1 have no Blocks.txt —
# their boundaries come from data/scripts/unicode_1_0_blocks.tsv.
# ─────────────────────────────────────────────────────────────────────────────

# Ordered minor versions → source dir under data/unicode/ (matches
# tools/compute_version_stats.py SNAPSHOTS).
# Ordered minor versions -> source dir under data/unicode/.  The table is
# shared with the data downloader (babellib/tools/sync_data.py).
_VERSION_DIRS: list[tuple[str, str]] = VERSION_DIRS


@functools.lru_cache(maxsize=1)
def _find_file(base: Path, prefix: str) -> Path | None:
    """Find a data file named ``<prefix>…``.txt (not .html) in base."""
    for item in sorted(base.iterdir()):
        if item.is_file() and item.name.startswith(prefix) and item.name.endswith(".txt"):
            return item
    return None


_parse_blocks_file = Unicode._parse_blocks_file


def _assigned_codepoints(path: Path) -> list[int]:
    """Sorted assigned codepoints (ranges expanded) — reused from babelsoft.unicode.core."""
    return Unicode._assigned_codepoints(path)


@functools.lru_cache(maxsize=64)
def _usable_unicode_data_path(version: str) -> Path | None:
    """Path to the version's usable UnicodeData.txt, inheriting backwards.

    Same fallback chain as ``_version_blocks``: versions with compressed
    UnicodeData (1.1.5) or with no usable file (3.1.1) inherit the previous
    version's file; 1.0.0/1.0.1 use the reconstructed repertoire.
    """
    if version in ("1.0.0", "1.0.1"):
        p = _RECONSTRUCTED_DIR / version / "UnicodeData.txt"
        return p if p.exists() else None
    dirname = dict(_VERSION_DIRS).get(version)
    if dirname is None:
        return None
    base = Dirs.UNICODE / dirname
    ud = _find_file(base, "UnicodeData") if base.exists() else None
    if ud is not None and not _unicode_data_is_compressed(ud):
        return ud
    versions = [v for v, _ in _VERSION_DIRS]
    i = versions.index(version)
    if i > 0:
        return _usable_unicode_data_path(versions[i - 1])
    return None


@functools.lru_cache(maxsize=64)
def _version_unicode_data_path(version: str) -> Path | None:
    """Path to the version's OWN UnicodeData.txt (no compression inheritance).

    Reconstructed data for 1.0.0/1.0.1; the version's own file otherwise.
    Only inherits when the version ships no UnicodeData at all (e.g. 3.1.1).
    Unlike ``_usable_unicode_data_path`` this does NOT treat compressed files
    (1.1.5's <CJK IDEOGRAPH REPRESENTATIVE>) as unusable — the rest of those
    files is still real per-version data.
    """
    if version in ("1.0.0", "1.0.1"):
        p = _RECONSTRUCTED_DIR / version / "UnicodeData.txt"
        return p if p.exists() else None
    dirname = dict(_VERSION_DIRS).get(version)
    if dirname is None:
        return None
    base = Dirs.UNICODE / dirname
    ud = _find_file(base, "UnicodeData") if base.exists() else None
    if ud is not None:
        return ud
    versions = [v for v, _ in _VERSION_DIRS]
    i = versions.index(version)
    if i > 0:
        return _version_unicode_data_path(versions[i - 1])
    return None


@functools.lru_cache(maxsize=64)
def raw_codepoints_for(version: str) -> list[int]:
    """Sorted assigned codepoints from the version's own UnicodeData.

    1.0.0/1.0.1 use the reconstructed repertoire; 1.1.5 keeps its real data
    (Hangul at U+3400-4DFF, the CJK block reduced to its representative entry).
    """
    if version in ("1.0.0", "1.0.1"):
        return sorted(_reconstructed_codepoints(version) or [])
    path = _version_unicode_data_path(version)
    if path is None:
        return []
    return Unicode._assigned_codepoints(path)


@functools.lru_cache(maxsize=8)
def _ucd_entries_for(version: str) -> dict[int, dict]:
    """{cp: full 15-field UnicodeData entry} for the version's own file."""
    path = _version_unicode_data_path(version)
    if path is None:
        return {}
    return {e["cp"]: e for e in Unicode._unicodedata_file(path)}


@functools.lru_cache(maxsize=128)
def props_for_version(version: str, cp: int) -> dict | None:
    """Full UCD entry (cp/name/gc/ccc/bidi/decomp/dec/digit/num/mirrored/
    uni1/iso/up/lo/ti) for a codepoint in a given version, or None."""
    return _ucd_entries_for(version).get(cp)


@functools.lru_cache(maxsize=128)
def name_for_version(version: str, cp: int) -> str:
    """Name of a codepoint as encoded in a given Unicode version, or ``""``
    when unassigned / a range placeholder in that version."""
    e = props_for_version(version, cp)
    if not e:
        return ""
    n = e["name"]
    return "" if n.startswith("<") else n


@functools.lru_cache(maxsize=64)
def assigned_codepoints_for(version: str) -> list[int]:
    """Sorted assigned codepoints for a version, inheriting on unusable data.

    Same as ``raw_codepoints_for`` except compressed (1.1.5) or missing (3.1.1)
    UnicodeData inherits the previous version's full set — used where the whole
    repertoire matters (e.g. the version diff), not per-character history.
    """
    if version in ("1.0.0", "1.0.1"):
        return sorted(_reconstructed_codepoints(version) or [])
    path = _usable_unicode_data_path(version)
    if path is None:
        return []
    return Unicode._assigned_codepoints(path)


def _unicode_data_is_compressed(path: Path) -> bool:
    """Old 1.1-era files use a single '<CJK IDEOGRAPH REPRESENTATIVE>' entry."""
    for raw in path.read_text(encoding="utf-8", errors="ignore").splitlines():
        if "REPRESENTATIVE" in raw.upper():
            return True
    return False


def _count_in_range(cps: list[int], start: int, end: int) -> int:
    return bisect.bisect_right(cps, end) - bisect.bisect_left(cps, start)


@functools.lru_cache(maxsize=1)
def _version_blocks() -> dict[str, list[dict]]:
    """{minor version: [{name, start, end, chars, version}, ...]}.

    Built from each version's own Blocks.txt (block list) and UnicodeData
    (character counts).  ``version`` is the earliest version in which that block
    name first appears.
    """
    result: dict[str, list[dict]] = {}
    introduced: dict[str, str] = {}
    prev_ranges: list[tuple[str, int, int]] | None = None
    prev_entries: list[dict] | None = None

    for version, dirname in _VERSION_DIRS:
        base = Dirs.UNICODE / dirname

        if version in ("1.0.0", "1.0.1"):
            entries = _reconstructed_blocks(version) or []
            for b in entries:
                introduced.setdefault(b["name"], b["version"])
            prev_ranges = [(b["name"], b["start"], b["end"]) for b in entries]
            prev_entries = entries
            result[version] = entries
            continue

        blk = _find_file(base, "Blocks")
        if blk is not None:
            prev_ranges = _parse_blocks_file(blk)

        ud = _find_file(base, "UnicodeData")
        if ud is not None and not _unicode_data_is_compressed(ud):
            cps = _assigned_codepoints(ud)
            entries = []
            for name, start, end in prev_ranges or []:
                chars = _count_in_range(cps, start, end)
                if chars > 0:
                    entries.append({"name": name, "start": start, "end": end, "chars": chars})
        else:
            # no usable UnicodeData — repertoire identical to the previous version
            entries = [dict(e) for e in (prev_entries or [])]

        for b in entries:
            if b["name"] not in introduced:
                introduced[b["name"]] = version
            b["version"] = introduced[b["name"]]

        result[version] = entries
        prev_entries = entries
    return result


def blocks_for_version(version: str) -> list[dict]:
    """Return the block list for a given Unicode version, read from that version's UCD."""
    return _version_blocks().get(version, [])


def all_versions() -> list[dict]:
    """Return all known Unicode versions (1.0.0 … 17.0.0) with dates.

    The full list comes from the version-history table
    (data/scripts/unicode_version_stats.tsv).
    """
    return [{"version": h["version"], "date": h["date"]} for h in version_history(_DEFAULT_BLOCKS)]
